// The how-to guides site is Astro Starlight (packages/guides-site): its search, docs layout and phone menu. This
// module turns the guides and their captures into Starlight's input: one Markdown page per guide, an index and a page
// per audience, the sidebar grouped by audience, and where each captured file goes. Pure: the CLI (scripts/guide.mjs)
// writes the files and runs the build.
import YAML from 'yaml';
import { GLOSSARY_WORDS, glossaryPage, linkTerms } from './glossary.mjs';
import { AUDIENCES } from './model.mjs';
import { escapeHtml, escapeMarkdown } from './text.mjs';

export { escapeHtml, escapeMarkdown };

/**
 * One appearance's colour tokens from packages/ui/src/theme.css (`@variant <light|dark> { --color-…: … }`), so the
 * site follows the app's palette without a copy of it.
 */
export function themeTokens(css, variant = 'dark') {
  const start = css.indexOf(`@variant ${variant}`);
  if (start < 0) throw new Error(`theme.css has no \`@variant ${variant}\` block`);
  const open = css.indexOf('{', start);
  let depth = 0;
  let end = open;
  for (; end < css.length; end++) {
    if (css[end] === '{') depth++;
    else if (css[end] === '}' && --depth === 0) break;
  }
  const block = css.slice(open + 1, end).replace(/\/\*[\s\S]*?\*\//g, '');
  return Object.fromEntries([...block.matchAll(/(--color-[\w-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
}

/** Both appearances as the stylesheet the site's brand.css reads: Starlight sets `data-theme` on <html>. */
export function tokensCss({ light, dark }) {
  const vars = (tokens) => Object.entries(tokens).map(([k, v]) => `  ${k}: ${v};`);
  return `/* Generated by pnpm guide from packages/ui/src/theme.css. Do not edit. */
:root,
:root[data-theme='light'] {
${vars(light).join('\n')}
}
:root[data-theme='dark'] {
${vars(dark).join('\n')}
}
`;
}

/**
 * The site's words. Placeholder copy in a plain voice: a project rewrites them in its own and gets the human's yes
 * (they are new copy). No name, place, time or count from the seed.
 */
export const SITE = {
  title: 'How-to guides',
  intro: 'The app, one screen at a time.',
  steps: (n) => `${n} ${n === 1 ? 'step' : 'steps'}`,
  draft: 'Draft',
  noGuides: 'No guides yet.',
  clipFallback: 'Your browser can’t play this clip.',
};

export const LANDING = {
  search: 'Search',
  audiencesTitle: 'Guides',
  guides: (n) => (n ? `${n} ${n === 1 ? 'guide' : 'guides'}` : SITE.noGuides),
  openInApp: 'Open in the app',
  /** The end of a guide. */
  done: 'Done.',
};

/** A base path as Astro wants it: `/` or `/name/`. */
export function normalizeBase(base = '/') {
  const parts = String(base).split('/').filter(Boolean);
  return parts.length ? `/${parts.join('/')}/` : '/';
}

const frontmatter = (data) => `---\n${YAML.stringify(data, { lineWidth: 0 })}---\n`;

/** A quiet progress line over a guide's steps: site.js fills it as the steps scroll past. */
function progress(n) {
  return `<div class="guide-progress" aria-hidden="true" data-steps="${n}"><span></span></div>`;
}

/**
 * Starlight's input from the guides and what was captured for each (`captures[slug] = { steps: [{ image, clip,
 * width, height }] }`), for a site served under `base`. `app` is harness.config.json's `app` (its name titles the
 * site; its scheme makes a guide's "Open in the app" link).
 *
 * - `pages`: each guide's Markdown page by path under src/content/docs/ (`<audience>/<slug>/index.md`);
 * - `media`: each captured file to copy (`guide`, its file name `from`, and `to`): a still goes beside its page under
 *   `content/` (Astro sizes and compresses it), a clip, its poster and each guide's first still (the audience page's
 *   thumbnail) under `public/` (served as they are);
 * - `site`: what the landing and audience pages (packages/guides-site/src/pages) and the sidebar read;
 * - `glossary`: the terms the site shows (glossary.mjs `siteGlossary`): a page of them, and each caption's first
 *   use of one in a guide linked to it;
 * - `skipped`: guides without a capture, or whose steps no longer match it (build them again). Captions can change
 *   without a rebuild; steps can't.
 */
export function renderContent({ guides, captures, base = '/', glossary = [], app = { name: 'The app', scheme: 'app' } }) {
  base = normalizeBase(base);
  const pages = new Map();
  const media = [];
  const skipped = [];
  const built = guides.filter((g) => {
    const c = captures[g.slug];
    if (!c) skipped.push({ guide: g, reason: 'not built yet' });
    else if (c.steps.length !== g.steps.length) skipped.push({ guide: g, reason: `captured ${c.steps.length} steps, the guide has ${g.steps.length}` });
    else return true;
    return false;
  });
  const byAudience = AUDIENCES.map((a) => ({ ...a, guides: built.filter((g) => g.audience === a.id) }));

  for (const a of byAudience) {
    a.guides.forEach((g, order) => {
      const dir = `${a.id}/${g.slug}`;
      const shots = captures[g.slug].steps;
      const seen = new Set();
      const steps = g.steps.map((s, i) => {
        const shot = shots[i];
        let picture;
        if (shot.clip) {
          media.push({ guide: g, from: shot.clip, to: `public/${dir}/${shot.clip}` }, { guide: g, from: shot.image, to: `public/${dir}/${shot.image}` });
          const size = shot.width && shot.height ? ` width="${shot.width}" height="${shot.height}"` : '';
          picture = `<div class="phone"><video src="${escapeHtml(`${base}${dir}/${shot.clip}`)}" poster="${escapeHtml(`${base}${dir}/${shot.image}`)}" muted loop playsinline controls preload="metadata" data-autoplay data-pagefind-ignore aria-label="${escapeHtml(s.alt)}"${size}>${escapeHtml(SITE.clipFallback)}</video></div>`;
        } else {
          media.push({ guide: g, from: shot.image, to: `content/${dir}/${shot.image}` });
          picture = `<div class="phone">\n\n   ![${escapeMarkdown(s.alt)}](./${shot.image})\n\n   </div>`;
        }
        return `${i + 1}. ${linkTerms(s.caption, glossary, seen, `${base}glossary/`)}\n\n   ${picture}\n`;
      });
      if (!shots[0].clip) media.push({ guide: g, from: shots[0].image, to: `public/${dir}/${shots[0].image}` });
      const sidebar = { order: order + 1, ...(g.copy === 'placeholder' ? { badge: { text: SITE.draft, variant: 'caution' } } : {}) };
      const open = g.open ? `<a class="guide-open" href="${escapeHtml(`${app.scheme}://${g.open}`)}">${escapeHtml(LANDING.openInApp)} →</a>\n` : '';
      pages.set(
        `${dir}/index.md`,
        `${frontmatter({ title: g.title, ...(g.summary ? { description: g.summary } : {}), sidebar })}
<p class="guide-kicker">${escapeHtml(`${a.name} · ${SITE.steps(g.steps.length)}`)}</p>
${g.copy === 'placeholder' ? `<p class="guide-badge">${escapeHtml(SITE.draft)}</p>\n` : ''}${g.summary ? `<p class="guide-lede">${escapeHtml(g.summary)}</p>\n` : ''}${open}${progress(g.steps.length)}

<div class="guide-steps">

${steps.join('\n')}
</div>

<p class="guide-done" data-pagefind-ignore>${escapeHtml(LANDING.done)}</p>
`,
      );
    });
  }

  if (glossary.length) pages.set('glossary/index.md', glossaryPage(glossary));

  const audiences = byAudience.map((a) => ({
    id: a.id,
    name: a.name,
    count: LANDING.guides(a.guides.length),
    guides: a.guides.map((g) => ({
      title: g.title,
      summary: g.summary,
      href: `${a.id}/${g.slug}/`,
      steps: SITE.steps(g.steps.length),
      thumb: `${a.id}/${g.slug}/${captures[g.slug].steps[0].image}`,
      draft: g.copy === 'placeholder',
    })),
  }));
  const site = {
    name: app.name,
    sidebar: [
      ...byAudience.filter((a) => a.guides.length).map((a) => ({ label: a.name, items: a.guides.map((g) => `${a.id}/${g.slug}`) })),
      ...(glossary.length ? ['glossary'] : []),
    ],
    glossary: glossary.length ? { href: 'glossary/', ...GLOSSARY_WORDS } : null,
    words: { ...SITE, ...LANDING, footer: app.name, steps: undefined, guides: undefined },
    audiences,
  };
  return { pages, media, site, skipped, built, base };
}
