// Shared helpers for the harness scripts: repo root, the project config, .env.local parsing and regeneration.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';

export const ROOT = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim();
export const ROOT_ENV = path.join(ROOT, '.env.local');
export const MOBILE_ENV = path.join(ROOT, 'apps/mobile/.env.local');

/**
 * The project's identity (harness.config.json) and the machine-wide names derived from it. Scripts read these at
 * run time, so they stay byte-identical across projects made from the template (`pnpm harness:diff` relies on it).
 */
export const CONFIG = JSON.parse(readFileSync(path.join(ROOT, 'harness.config.json'), 'utf8'));
export const APP = {
  name: CONFIG.app.name,
  slug: CONFIG.app.slug,
  scheme: CONFIG.app.scheme,
  bundleId: CONFIG.app.bundleId,
  androidPackage: CONFIG.app.androidPackage ?? CONFIG.app.bundleId,
  /** Machine-wide state shared by every worktree of this project: slots, locks, the native build cache. */
  home: path.join(os.homedir(), `.${CONFIG.app.slug}`),
};

/** Parse KEY='value' / KEY=value lines. */
export function parseEnv(text) {
  const out = {};
  for (const line of text.split('\n')) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (!m) continue;
    let v = m[2].trim();
    if ((v.startsWith("'") && v.endsWith("'")) || (v.startsWith('"') && v.endsWith('"'))) v = v.slice(1, -1);
    out[m[1]] = v;
  }
  return out;
}

export function readEnv(file = ROOT_ENV) {
  return existsSync(file) ? parseEnv(readFileSync(file, 'utf8')) : {};
}

function writeEnvFile(file, vars, header) {
  const body = Object.entries(vars)
    .filter(([, v]) => v !== undefined && v !== '')
    .map(([k, v]) => `${k}=${v}`)
    .join('\n');
  writeFileSync(file, `# ${header}\n${body}\n`);
}

/**
 * Regenerate .env.local (root, for scripts and integration tests) and apps/mobile/.env.local
 * (EXPO_PUBLIC_* for the app) from the running stack. Call after every `supabase stack start`:
 * ports are automatic and the DB port can move after a destroy.
 */
export function regenerateEnv(slot = {}) {
  const raw = execFileSync('supabase', ['stack', 'status', '--env', '--output-format', 'text'], {
    cwd: ROOT,
    encoding: 'utf8',
    env: { ...process.env, SUPABASE_EXPERIMENTAL_STACK: '1' },
  });
  const sb = parseEnv(raw);
  const header = 'Generated by the harness (pnpm wt up / pnpm sb start). Do not edit or commit.';
  writeEnvFile(ROOT_ENV, { ...sb, WT_SLOT: slot.k, METRO_PORT: slot.metroPort }, header);
  writeEnvFile(
    MOBILE_ENV,
    {
      EXPO_PUBLIC_SUPABASE_URL: sb.API_URL,
      EXPO_PUBLIC_SUPABASE_ANON_KEY: sb.ANON_KEY,
      EXPO_PUBLIC_WT_SLOT: slot.k,
      EXPO_PUBLIC_METRO_PORT: slot.metroPort,
      // Kept across restarts: `pnpm guide serve --set-help-url` points the app's Help row at this slot's guides site.
      EXPO_PUBLIC_GUIDES_URL: readEnv(MOBILE_ENV).EXPO_PUBLIC_GUIDES_URL,
    },
    header,
  );
  return sb;
}

/**
 * This worktree's slot (`.wt/state.json`), only while the worktree still owns it. A released slot can be claimed
 * by another worktree, and its stale state.json would point a script at that agent's simulator and Metro.
 */
export function readSlotState() {
  const file = path.join(ROOT, '.wt/state.json');
  const state = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : null;
  const owner = state && path.join(APP.home, 'slots', String(state.slot), 'path');
  if (!state || !existsSync(owner) || readFileSync(owner, 'utf8').trim() !== ROOT) {
    console.error('this worktree holds no slot: run `pnpm wt up` first');
    process.exit(1);
  }
  return state;
}

/** Maestro on PATH or in ~/.maestro/bin. */
export function maestroBin() {
  return [path.join(os.homedir(), '.maestro/bin/maestro'), 'maestro'].find((m) => m === 'maestro' || existsSync(m));
}

/** The `-e` flags every Maestro flow gets: this app, this slot, this stack's Mailpit. Flows use ${APP_ID}, ${SCHEME}. */
export function maestroEnv(state, extra = {}) {
  const vars = {
    APP_ID: APP.bundleId,
    SCHEME: APP.scheme,
    METRO_PORT: state.metroPort,
    WT_SLOT: state.slot,
    // The local Mailpit, where Supabase Auth sends sign-in codes (flows read them over HTTP).
    MAILPIT_URL: readEnv().MAILPIT_URL ?? '',
    ...extra,
  };
  return Object.entries(vars).flatMap(([k, v]) => ['-e', `${k}=${v}`]);
}
