// Brand for the native chrome: Expo Router's NativeTabs (UITabBar / Material bottom navigation) and the native
// stack header. The OS draws both, owns safe areas and edges, and we style them only through their props.
// Colours come from theme.css (read live, so they follow the theme); app code spreads these hooks and never
// passes colours or fonts itself. Every knob used here, and the ones the API lacks, is listed in the
// design-system skill ("Native chrome").
import type { ImageSourcePropType } from 'react-native';
import { useCSSVariable } from 'uniwind';
import { FONT } from './fonts';
import { haptics } from './haptics';
import type { TabIconName } from './icons';

/**
 * The tab glyphs (Phosphor, src/lib/icons.ts) as template PNGs: `regular` unselected, `fill` selected. Generated by
 * `pnpm --filter @app/ui tab-icons`; NativeTabs takes images, not components.
 */
export const tabIcons: Record<TabIconName, { default: ImageSourcePropType; selected: ImageSourcePropType }> = {
  home: { default: require('../../assets/tab-icons/home.png'), selected: require('../../assets/tab-icons/home-selected.png') },
  items: { default: require('../../assets/tab-icons/items.png'), selected: require('../../assets/tab-icons/items-selected.png') },
  me: { default: require('../../assets/tab-icons/me.png'), selected: require('../../assets/tab-icons/me-selected.png') },
};

/** Tab label type. The native label style takes family, size, weight and colour only (no textTransform, no tracking). */
export const tabLabelFont = { ...FONT.tabLabel, fontSize: 10 };

function useToken(name: string, fallback: string): string {
  return (useCSSVariable(`--color-${name}`) as string | undefined) ?? fallback;
}

/** Hex + alpha (0..1) as #rrggbbaa. */
function withAlpha(hex: string, alpha: number) {
  const a = Math.round(alpha * 255)
    .toString(16)
    .padStart(2, '0');
  return hex.length === 7 ? `${hex}${a}` : hex;
}

/**
 * Props for `<NativeTabs {...useNativeTabsTheme()}>`: the selected tab is `primary`, the rest `muted-foreground`.
 * On Android the Material indicator is a `primary` pill with the icon knocked out in `primary-foreground`, the bar
 * sits on `surface` and the ripple is a 12 % foreground wash. On iOS 26 the system draws the Liquid Glass
 * background, so the background props only apply on iOS 18 and earlier. PROJECT: tune these to the brand.
 */
export function useNativeTabsTheme() {
  const foreground = useToken('foreground', '#111827');
  const muted = useToken('muted-foreground', '#6b7280');
  const surface = useToken('surface', '#f3f4f6');
  const primary = useToken('primary', '#111827');
  const onPrimary = useToken('primary-foreground', '#ffffff');
  const android = process.env.EXPO_OS === 'android';
  return {
    tintColor: primary,
    iconColor: { default: muted, selected: android ? onPrimary : primary },
    labelStyle: {
      default: { ...tabLabelFont, color: muted },
      selected: { ...tabLabelFont, color: primary },
    },
    backgroundColor: surface,
    // iOS 18 and earlier: the classic bar. A thin material over the surface, no hairline shadow.
    blurEffect: 'systemChromeMaterial' as const,
    shadowColor: 'transparent',
    disableTransparentOnScrollEdge: true,
    // iOS 26: the glass bar shrinks to the active tab while you read, and comes back when you scroll up.
    minimizeBehavior: 'onScrollDown' as const,
    // Badges: a primary dot or count.
    badgeBackgroundColor: primary,
    badgeTextColor: onPrimary,
    // Android Material 3
    indicatorColor: primary,
    rippleColor: withAlpha(foreground, 0.12),
    labelVisibilityMode: 'labeled' as const,
    // A selection haptic when the tab actually changes (not on re-tapping the current one).
    screenListeners: ({ navigation }: { navigation: { isFocused: () => boolean } }) => ({
      tabPress: () => {
        if (!navigation.isFocused()) haptics.select();
      },
    }),
  };
}

/**
 * `screenOptions` for every native Stack: the brand's title fonts (large titles on iOS tab roots), the theme's
 * ground behind the content, no header hairline, a minimal back button. Spread it, then add per-screen options.
 * `ground: 'ink'` is the forced night ground (a full-screen moment that reads dark in both themes).
 *
 * `header: 'opaque'` for stacks of forms (sign-in, onboarding): the iOS bar stops floating over the content. With a
 * floating bar, React Native's keyboard inset handling (`automaticallyAdjustKeyboardInsets`) scrolls a short form
 * up under the header when the keyboard opens; an opaque bar keeps the content below it.
 */
export function useStackTheme({ ground = 'background', header = 'floating' }: { ground?: 'background' | 'ink'; header?: 'floating' | 'opaque' } = {}) {
  const themeForeground = useToken('foreground', '#111827');
  const themeBackground = useToken('background', '#ffffff');
  const ink = useToken('ink', '#050608');
  const onInk = useToken('on-ink', '#f3f4f6');
  const foreground = ground === 'ink' ? onInk : themeForeground;
  const background = ground === 'ink' ? ink : themeBackground;
  const ios = process.env.EXPO_OS === 'ios';
  return {
    headerTintColor: foreground,
    headerTitleStyle: { ...FONT.title, fontSize: 17, color: foreground },
    headerLargeTitleStyle: { ...FONT.largeTitle, fontSize: 34, color: foreground },
    headerShadowVisible: false,
    headerLargeTitleShadowVisible: false,
    headerBackButtonDisplayMode: 'minimal' as const,
    // iOS: the bar floats over the content and iOS 26 draws its own scroll-edge effect (no blurEffect: the two
    // overlap); Android: an opaque Material top bar.
    headerTransparent: ios && header === 'floating',
    headerLargeStyle: { backgroundColor: header === 'opaque' ? background : 'transparent' },
    headerStyle: ios && ground === 'background' && header === 'floating' ? undefined : { backgroundColor: background },
    contentStyle: { backgroundColor: background },
  };
}

/** Colours for Expo Router's `ThemeProvider` (React Navigation theme): what the navigators paint between screens. */
export function useNavigationColors() {
  return {
    primary: useToken('foreground', '#111827'),
    background: useToken('background', '#ffffff'),
    card: useToken('background', '#ffffff'),
    text: useToken('foreground', '#111827'),
    border: useToken('hairline', '#e5e7eb'),
    notification: useToken('foreground', '#111827'),
  };
}
